#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';

const require = createRequire(import.meta.url);
const rootDir = process.cwd();
const postsDir = path.join(rootDir, 'posts');
const outputFile = path.join(rootDir, 'lib', 'generated', 'lowlight-languages.ts');

const PROJECT_ALIASES = {
  redis: 'bash',
  shell: 'bash',
  sh: 'bash',
  cs: 'csharp',
  yml: 'yaml',
  plain: 'plaintext',
  text: 'plaintext',
  mdx: 'javascript',
  jsx: 'javascript',
  tsx: 'typescript',
  html: 'xml',
  svg: 'xml',
  js: 'javascript',
  ts: 'typescript',
  py: 'python',
  rb: 'ruby',
  kt: 'kotlin',
  'c++': 'cpp',
  'c#': 'csharp',
};

function collectPostFiles(directory, files = []) {
  if (!fs.existsSync(directory)) return files;

  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const fullPath = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      collectPostFiles(fullPath, files);
    } else if (/\.mdx?$/i.test(entry.name)) {
      files.push(fullPath);
    }
  }

  return files;
}

function scanFenceLanguages(filePath, languages) {
  const lines = fs.readFileSync(filePath, 'utf8').split(/\r?\n/);
  let activeFence = null;

  lines.forEach((line, index) => {
    if (activeFence) {
      const closePattern = new RegExp(`^ {0,3}${activeFence.marker}{${activeFence.length},}[ \\t]*$`);
      if (closePattern.test(line)) activeFence = null;
      return;
    }

    const opening = line.match(/^ {0,3}(`{3,}|~{3,})(.*)$/);
    if (!opening) return;

    activeFence = { marker: opening[1][0], length: opening[1].length };
    const language = opening[2].trim().match(/^([^\s{]+)/)?.[1]?.toLowerCase();
    if (!language || languages.has(language)) return;

    languages.set(language, {
      file: path.relative(rootDir, filePath).replace(/\\/g, '/'),
      line: index + 1,
    });
  });
}

function loadHighlightLanguageIndex() {
  const corePath = require.resolve('highlight.js/lib/core');
  const packageRoot = path.dirname(path.dirname(corePath));
  const languagesDir = path.join(packageRoot, 'lib', 'languages');
  const supportedLanguagesFile = path.join(packageRoot, 'SUPPORTED_LANGUAGES.md');
  const available = new Set(
    fs.readdirSync(languagesDir)
      .filter((name) => name.endsWith('.js') && !name.endsWith('.min.js'))
      .map((name) => name.slice(0, -3)),
  );
  const aliases = new Map();
  const rows = fs.readFileSync(supportedLanguagesFile, 'utf8').split(/\r?\n/);

  for (const row of rows) {
    const columns = row.match(/^\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]*?)\s*\|/);
    if (!columns) continue;

    const rowAliases = columns[2]
      .split(',')
      .map((alias) => alias.trim().toLowerCase())
      .filter(Boolean);
    const canonical = rowAliases.find((alias) => available.has(alias));
    if (!canonical) continue;

    for (const alias of rowAliases) {
      const previous = aliases.get(alias);
      aliases.set(alias, previous && previous !== canonical ? null : canonical);
    }
  }

  return { available, aliases };
}

function resolveLanguages(scannedLanguages, languageIndex) {
  const languageMap = { plaintext: 'plaintext' };
  const canonicalLanguages = new Set(['plaintext']);
  const unsupported = [];

  for (const [language, location] of [...scannedLanguages].sort(([a], [b]) => a.localeCompare(b))) {
    if (language === 'mermaid') {
      languageMap[language] = 'mermaid';
      continue;
    }

    const projectTarget = PROJECT_ALIASES[language];
    const officialTarget = languageIndex.aliases.get(language);
    const target = projectTarget ||
      (languageIndex.available.has(language) ? language : officialTarget);

    if (target && languageIndex.available.has(target)) {
      languageMap[language] = target;
      canonicalLanguages.add(target);
    } else {
      languageMap[language] = 'plaintext';
      unsupported.push({ language, ...location });
    }
  }

  return {
    languageMap,
    canonicalLanguages: [...canonicalLanguages].sort(),
    unsupported,
  };
}

function createGeneratedModule({ languageMap, canonicalLanguages, unsupported }) {
  const imports = canonicalLanguages
    .map((language, index) =>
      `import language${index} from 'highlight.js/lib/languages/${language}';`,
    )
    .join('\n');
  const registrations = canonicalLanguages
    .map((language, index) => `  ${JSON.stringify(language)}: language${index},`)
    .join('\n');

  return `// This file is generated by scripts/generate-lowlight-languages.js.\n` +
    `// Do not edit it manually.\n\n` +
    `import { createLowlight } from 'lowlight';\n` +
    `${imports}\n\n` +
    `export const generatedLowlight = createLowlight({\n${registrations}\n});\n\n` +
    `export const generatedLanguageMap: Readonly<Record<string, string>> = Object.freeze(` +
    `${JSON.stringify(languageMap, null, 2)});\n\n` +
    `export const generatedUnsupportedLanguages = ` +
    `${JSON.stringify(unsupported.map(({ language }) => language), null, 2)} as const;\n`;
}

function writeIfChanged(content) {
  fs.mkdirSync(path.dirname(outputFile), { recursive: true });
  if (fs.existsSync(outputFile) && fs.readFileSync(outputFile, 'utf8') === content) {
    return false;
  }

  const temporaryFile = `${outputFile}.tmp`;
  fs.writeFileSync(temporaryFile, content, 'utf8');
  fs.renameSync(temporaryFile, outputFile);
  return true;
}

function main() {
  const scannedLanguages = new Map();
  const postFiles = collectPostFiles(postsDir).sort();
  for (const filePath of postFiles) scanFenceLanguages(filePath, scannedLanguages);

  const result = resolveLanguages(scannedLanguages, loadHighlightLanguageIndex());
  const changed = writeIfChanged(createGeneratedModule(result));
  const supportedCount = Object.values(result.languageMap)
    .filter((language) => language !== 'plaintext' && language !== 'mermaid').length;

  console.log(
    `🔤 Lowlight languages: ${result.canonicalLanguages.length} grammars, ` +
    `${supportedCount} highlighted fence labels${changed ? ' (updated)' : ''}.`,
  );
  if (result.unsupported.length > 0) {
    console.warn('Plaintext fallback for unsupported fence labels:');
    for (const item of result.unsupported) {
      console.warn(`  - ${item.language} (${item.file}:${item.line})`);
    }
  }
}

main();